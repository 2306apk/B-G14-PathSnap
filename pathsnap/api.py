"""Laptop 1: FastAPI prediction/evaluation service for two-laptop LAN deployment.

References are read after inference solely to calculate aggregated metrics.
Reference road-segment IDs/geometry are NEVER included in API responses.
"""
from __future__ import annotations
import os,logging,time
from functools import lru_cache
from pathlib import Path
from dataclasses import dataclass,replace
import numpy as np
from fastapi import FastAPI,HTTPException
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel,Field
from .data import list_trips,load_trip
from .pipeline import load_model,predict
from .labels import approximate_reference_labels
from .metrics import get_metrics

logging.basicConfig(level=logging.INFO,format='%(asctime)s %(levelname)s %(message)s')
log=logging.getLogger('pathsnap.api')
DATA_ROOT=Path(os.getenv('PATHSNAP_DATA_ROOT','data'))
MODEL_PATH=Path(os.getenv('PATHSNAP_MODEL_PATH','artifacts/best_tuned.joblib'))
app=FastAPI(title='PathSnap API',version='0.1.0')
# Intended only for a private two-laptop LAN. Firewall port 8000 on public networks.
app.add_middleware(CORSMiddleware,allow_origins=['*'],allow_methods=['GET','POST'],allow_headers=['*'])


class TripRequest(BaseModel):
    trip_id: str=Field(pattern=r'^\d{8}$')


def active_partition() -> str:
    # Evaluator trips are absent from the uploaded student ZIP. Do not invent IDs.
    return 'evaluator_test' if list_trips(DATA_ROOT,'evaluator_test') else 'student_test'


@app.get('/health')
def health():
    return {'status':'ok','model_loaded':MODEL_PATH.is_file(),'partition':active_partition(),
            'trip_count':len(list_trips(DATA_ROOT,active_partition()))}


@app.get('/trips')
def trips():
    split=active_partition()
    return {'partition':split,'trips':list_trips(DATA_ROOT,split),
            'note':'Evaluator data is absent; student-testing demo displayed' if split=='student_test' else 'Reserved evaluator trips'}


@lru_cache(maxsize=1)
def model_bundle():
    return load_model(MODEL_PATH)


@lru_cache(maxsize=12)
def run_trip(trip_id: str):
    split=active_partition()
    if trip_id not in list_trips(DATA_ROOT,split):
        raise FileNotFoundError('Trip not found in the currently active partition')
    print(f'PREDICT_REQUEST partition={split} trip_id={trip_id}',flush=True)
    started=time.perf_counter()
    # Predicted route cannot see labels; leave reference .route unread until afterwards.
    trip=load_trip(DATA_ROOT,split,trip_id,include_reference=False)
    bundle=model_bundle()
    predicted=predict(trip,bundle)
    inference_s=time.perf_counter()-started
    selected_arc_ids=predicted['hmm'].astype(int)
    raw=trip.track[:,[1,0]]
    # Compact geometry: unique selected arcs, in local trip network only.
    unique_arc=np.unique(selected_arc_ids)
    matched=[[
        trip.nodes[trip.arcs[int(a),0],[1,0]].tolist(),
        trip.nodes[trip.arcs[int(a),1],[1,0]].tolist()]
        for a in unique_arc]
    # Bounding-region road sample, with no hidden references.
    a=trip.arcs
    mids=(trip.nodes[a[:,0]]+trip.nodes[a[:,1]])*.5
    min_lon,min_lat=np.min(trip.track[:,:2],axis=0)-.006
    max_lon,max_lat=np.max(trip.track[:,:2],axis=0)+.006
    nearby=np.where((mids[:,0]>=min_lon)&(mids[:,0]<=max_lon)&(mids[:,1]>=min_lat)&(mids[:,1]<=max_lat))[0][:1400]
    road=[[
        trip.nodes[trip.arcs[int(arc),0],[1,0]].tolist(),
        trip.nodes[trip.arcs[int(arc),1],[1,0]].tolist()]
        for arc in nearby]
    scores=None
    # Ground-truth file is accessed exclusively here, post-inference.
    ref_path=DATA_ROOT/split/trip_id/(trip_id+'.route')
    if ref_path.exists():
        with_ref=load_trip(DATA_ROOT,split,trip_id,include_reference=True)
        truth,alignment_error=approximate_reference_labels(with_ref)
        scores=get_metrics(trip,predicted['batch'].arc_ids,predicted['prob'],truth,selected_arc_ids)
        scores.pop('candidate_confusion_matrix',None)
        scores['median_reference_alignment_error_m']=float(np.median(alignment_error))
        scores['metric_note']='Approximate reference-geometry alignment; no per-observation ground truth provided'
    response={'trip_id':trip_id,'partition':split,'observations':len(trip.track),
        'inference_seconds':round(inference_s,3),
        'raw_gps_latlon':raw[::max(1,len(raw)//3000)].tolist(),
        'predicted_segments_latlon':matched,'nearby_roads_latlon':road,
        'metrics':scores,
        'prediction_note':'All predictions generated by the trained model + HMM, not by reference labels'}
    log.info('INFERENCE trip=%s split=%s observations=%s seconds=%.3f accuracy=%s',
             trip_id,split,len(trip.track),inference_s,scores['hmm_observation_accuracy'] if scores else 'N/A')
    return response


@app.post('/predict')
def predict_post(request:TripRequest):
    try:return run_trip(request.trip_id)
    except FileNotFoundError as err:raise HTTPException(status_code=404,detail=str(err)) from err
    except Exception:
        log.exception('Prediction pipeline failed for trip %s',request.trip_id)
        raise HTTPException(status_code=500,detail='Prediction pipeline error (see server logs)')


@app.get('/predict/{trip_id}')
def predict_get(trip_id:str):
    return predict_post(TripRequest(trip_id=trip_id))
